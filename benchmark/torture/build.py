#!/usr/bin/env python3
"""Build the complete finite DMG audio suite, or a standalone named case."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

from cases import catalog, FRAME_STEP, FRAME

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--case', help='Exact case name; retains its full-suite ID')
    parser.add_argument('--list', action='store_true')
    parser.add_argument('--out', type=Path, help='Output directory (default artifacts/torture/full or cases/NAME)')
    args = parser.parse_args()
    cases = [(i, case) for i, case in enumerate(catalog(), 1)]
    if args.list:
        for i, case in cases:
            print(f'{i:04x}  {case.name}  {case.description}')
        return
    if args.case:
        cases = [(i, c) for i, c in cases if c.name == args.case]
        if not cases:
            parser.error(f'Unknown case {args.case!r}; use --list')
    if any(i >= 0xffff for i, c in cases):
        parser.error('Case ID collides with the uint16 protocol end ID')
    out = (args.out or ROOT / 'artifacts/torture' / ('cases/' + args.case if args.case else 'full')).resolve()
    out.mkdir(parents=True, exist_ok=True)
    table = []
    assembly = ['; Generated by benchmark/torture/build.py; edit cases.py, not this file.']
    for i, case in cases:
        label = f'Case_{i:04x}'
        table.append(f'    db BANK({label})\n    dw {label}\n    dw {i}')
        assembly += [f'\nSECTION "{case.name}", ROMX', f'{label}:', f'; {case.description}', *case.lines]
    (out / 'case_table.inc').write_text('\n'.join(table) + '\n    db 0\n')
    (out / 'cases.inc').write_text('\n'.join(assembly) + '\n')
    rom = out / 'audio-torture.gb'
    commands = [
        ['rgbasm', '-I', str(HERE) + '/', '-I', str(out) + '/', '-o', str(out / 'engine.o'), str(HERE / 'engine.asm')],
        ['rgblink', '-m', str(out / 'audio-torture.map'), '-n', str(out / 'audio-torture.sym'), '-o', str(rom), str(out / 'engine.o')],
        ['rgbfix', '-v', '-p', '0', '-t', 'DMG AUDIO LAB', '-m', '0x1b', '-r', '0x04', str(rom)],
    ]
    for command in commands:
        subprocess.run(command, check=True)
    symbols = (out / 'audio-torture.sym').read_text()
    positions = {}
    for bank, address, case_id in re.findall(r'^([0-9a-fA-F]+):([0-9a-fA-F]+) Case_([0-9a-fA-F]+)$', symbols, re.M):
        bank, address, case_id = int(bank, 16), int(address, 16), int(case_id, 16)
        if not 1 <= bank <= 255:
            raise RuntimeError('ROM bank exceeds the engine low-byte MBC5 switching range')
        positions[case_id] = {'bank': bank, 'address': address}
    assert len(positions) == len(cases)
    data = rom.read_bytes()
    assert data[0x147] == 0x1b and data[0x149] == 4
    assert data[0x14d] == (-sum(data[0x134:0x14d]) - 25) & 255
    assert int.from_bytes(data[0x14e:0x150], 'big') == (sum(data[:0x14e]) + sum(data[0x150:])) & 65535
    manifest = {
        'format': 'dmg-audio-torture-v1',
        'rom': str(rom), 'rom_sha256': digest(rom), 'rom_bytes': len(data),
        'behavior': 'Auto-start on power-on; one pass; silence after the final packet; no SRAM writes.',
        'clock_T_hz': 4194304,
        'protocol': {'sync': [0xd3, 0x91], 'bit_order': 'MSB first', 'symbol_T': FRAME_STEP,
                     'zero_hz': 2048, 'one_hz': 4096, 'header': ['kind', 'id_lo', 'id_hi', 'payload_length'],
                     'checksum': 'XOR of header and payload; sync excluded',
                     'kinds': {'1': 'case marker', '2': 'readback', '3': 'suite end'}, 'end_id': 65535,
                     'silence_each_side_T': FRAME},
        'markers': {'1': 'case acoustic packet starts', '2': 'stimulus starts', '3': 'stimulus ends',
                    '4': 'suite complete', '5': 'readback acoustic packet starts', '6': 'end acoustic packet starts'},
        'cases': [{'id': i, 'name': c.name, 'group': c.group, 'description': c.description,
                   'parameters': c.parameters, 'readback_labels': c.readback_labels,
                   'readback_length': len(c.readback_labels), **positions[i]} for i, c in cases],
        'commands': commands,
        'source_sha256': {str(path.relative_to(ROOT)): digest(path) for path in
                          [HERE / 'cases.py', HERE / 'build.py', HERE / 'engine.asm', HERE / 'macros.inc']},
        'generated_sha256': {p.name: digest(p) for p in [out / 'cases.inc', out / 'case_table.inc']},
        'timing_note': 'Capture marker/APU CSV timestamps are GB_run instruction boundaries, not exact bus writes. Generated ASM and encoded-bit spacing define the schedule; holds include all listed CPU instruction overhead outside wait_cycles.',
        'limits': ['Finite domain/transition coverage, not every possible register interleaving.',
                   'Analog output and chip-instance differences require interpretation; this ROM has no invented accuracy pass threshold.',
                   '48kHz recordings cannot resolve ultrasonic oscillator edges; readback and subsequent audible playback expose some retained effects.',
                   'No calibrated VIN input is supplied. The NR50 gain grid clears VIN bits; the full-byte interaction walk visits them but does not characterize external audio.'],
    }
    (out / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'{rom}\n{len(cases)} cases; {len(data)} bytes; SHA256 {digest(rom)}')


if __name__ == '__main__':
    main()
